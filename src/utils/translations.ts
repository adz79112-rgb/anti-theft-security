// Fallback helper to safely retrieve translations
const translationCache: Record<string, TranslationSchema> = {};

export function getTranslation(lang: Language | string): TranslationSchema {
  if (translationCache[lang]) {
    return translationCache[lang];
  }

  const chosen = (translations as Record<string, TranslationSchema>)[lang] || translations.fr || translations.ar || translations.en;
  
  const merged = {
    ...en,
    ...chosen,
  };
  
  translationCache[lang] = merged;
  return merged;
}
